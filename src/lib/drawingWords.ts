function shuffle<T>(arr: T[]): T[] {
  const copy = [...arr];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j]!, copy[i]!];
  }
  return copy;
}

export function pickWordChoices(count = 3): string[] {
  return shuffle(DRAWING_WORDS).slice(0, count);
}

/** Loose match: trims, collapses spaces, ignores ال-prefix and diacritics/tatweel. */
export function normalizeGuess(text: string): string {
  return text
    .trim()
    .replace(/[ً-ٰٟـ]/g, "")
    .replace(/\s+/g, " ")
    .replace(/^ال/, "")
    .replace(/[أإآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .toLowerCase();
}

export function isCorrectGuess(guess: string, word: string): boolean {
  return normalizeGuess(guess) === normalizeGuess(word);
}